// agentLocalKeyPath key_mode=agent_local 时，加密密码取自本机密钥文件（T2 操作员自管，Center 不知密钥）
const agentLocalKeyPath = "/etc/backup-agent/backup.key"

// agentKeysDir SSH 私钥目录（与 writeKeyFile 一致）
const agentKeysDir = "/etc/backup-agent/keys"

// writeRcloneConf 生成 rclone.conf 内容并写入文件
// 注意：调用者要持锁
func (u *Uploader) writeRcloneConf() error {
	// 保证目录存在
	dir := filepath.Dir(u.configPath)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("创建 rclone 配置目录: %w", err)
	}

	// 按 storage ID 排序保证输出稳定
	ids := make([]int64, 0, len(u.storages))
	for id := range u.storages {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })

	var buf bytes.Buffer
	buf.WriteString("# Auto-generated by backup-agent - DO NOT EDIT MANUALLY\n\n")

	// cryptIDs 记录本次成功渲染了 crypt 包裹节的存储 ID（C1，供 remoteTargetPath 决定上传前缀）。
	// 只有 conf 写入成功后才提交，避免"内存认为已加密、盘中却没有 section"的窗口期。
	cryptIDs := make(map[int64]bool)

	for _, id := range ids {
		s := u.storages[id]
		section, hasCrypt, err := renderSection(s)
		if err != nil {
			slog.Warn("跳过无法生成的 rclone 配置节", "storage", s.Name, "type", s.Type, "err", err)
			continue
		}
		if hasCrypt {
			cryptIDs[id] = true
		}
		buf.WriteString(section)
		buf.WriteString("\n")
	}

	// 写入文件（覆盖）
	if err := os.WriteFile(u.configPath, buf.Bytes(), 0o600); err != nil {
		return fmt.Errorf("写 rclone.conf: %w", err)
	}
	u.cryptSections = cryptIDs
	slog.Info("已写入 rclone 配置", "path", u.configPath, "storages", len(ids))
	return nil
}

// renderSection 生成一个 rclone 配置节，如：
//
//	[bc_14]
//	type = s3
//	provider = Other
//	endpoint = ...
//
// 存储启用加密时（C1），在基础 section 之后增渲染 crypt 包裹节 [bc_<id>_c]。
// 第二个返回值表示是否成功渲染了 crypt 节；加密密码不可用或 obscure 失败时
// 跳过 crypt 节并告警（返回 hasCrypt=false，不报错）——基础 section 保留，
// 但 uploader 不会把该存储当作已加密，上传前会报错而非静默降级明文。
func renderSection(s client.Storage) (string, bool, error) {
	name := remoteName(s.ID)
	cfg := s.Config

	getStr := func(k string) string {
		if v, ok := cfg[k]; ok {
			if str, ok := v.(string); ok {
				return str
			}
			return fmt.Sprintf("%v", v)
		}
		return ""
	}
	getBool := func(k string) bool {
		v, ok := cfg[k]
		if !ok {
			return false
		}
		switch t := v.(type) {
		case bool:
			return t
		case string:
			return t == "true" || t == "1"
		}
		return false
	}

	var b strings.Builder
	b.WriteString(fmt.Sprintf("[%s]\n", name))

	switch s.Type {
	case "sftp":
		host := getStr("host")
		if host == "" {
			return "", false, fmt.Errorf("sftp: missing host")
		}
		b.WriteString("type = sftp\n")
		b.WriteString("host = " + host + "\n")
		if port := getStr("port"); port != "" && port != "22" {
			b.WriteString("port = " + port + "\n")
		}
		if user := getStr("user"); user != "" {
			b.WriteString("user = " + user + "\n")
		}
		// 密钥优先，密码需要 obscure
		if key := getStr("private_key"); key != "" {
			// 写到临时文件，rclone 需要文件路径
			keyPath, err := writeKeyFile(name, key)
			if err != nil {
				return "", false, fmt.Errorf("写 SSH 密钥文件: %w", err)
			}
			b.WriteString("key_file = " + keyPath + "\n")
		} else if pass := getStr("password"); pass != "" {
			obscured, err := rcloneObscure(pass)
			if err != nil {
				return "", false, fmt.Errorf("obscure 密码: %w", err)
			}
			b.WriteString("pass = " + obscured + "\n")
		}

	case "ftp":
		host := getStr("host")
		if host == "" {
			return "", false, fmt.Errorf("ftp: missing host")
		}
		b.WriteString("type = ftp\n")
		b.WriteString("host = " + host + "\n")
		if port := getStr("port"); port != "" && port != "21" {
			b.WriteString("port = " + port + "\n")
		}
		if user := getStr("user"); user != "" {
			b.WriteString("user = " + user + "\n")
		}
		if pass := getStr("password"); pass != "" {
			obscured, err := rcloneObscure(pass)
			if err != nil {
				return "", false, fmt.Errorf("obscure 密码: %w", err)
			}
			b.WriteString("pass = " + obscured + "\n")
		}
		if getBool("tls") {
			b.WriteString("tls = true\n")
		}
		if getBool("explicit_tls") {
			b.WriteString("explicit_tls = true\n")
		}
		if getBool("no_check_certificate") {
			b.WriteString("no_check_certificate = true\n")
		}

	case "webdav":
		url := getStr("url")
		if url == "" {
			return "", false, fmt.Errorf("webdav: missing url")
		}
		b.WriteString("type = webdav\n")
		b.WriteString("url = " + url + "\n")
		if vendor := getStr("vendor"); vendor != "" {
			b.WriteString("vendor = " + vendor + "\n")
		} else {
			b.WriteString("vendor = other\n")
		}
		if user := getStr("user"); user != "" {
			b.WriteString("user = " + user + "\n")
		}
		if pass := getStr("password"); pass != "" {
			obscured, err := rcloneObscure(pass)
			if err != nil {
				return "", false, fmt.Errorf("obscure 密码: %w", err)
			}
			b.WriteString("pass = " + obscured + "\n")
		}

	case "s3":
		endpoint := getStr("endpoint")
		bucket := getStr("bucket")
		ak := getStr("access_key_id")
		sk := getStr("secret_access_key")
		if endpoint == "" || ak == "" || sk == "" {
			return "", false, fmt.Errorf("s3: missing endpoint/access_key/secret")
		}
		_ = bucket // bucket 是路径的一部分，不写到 config，写到 remote path
		b.WriteString("type = s3\n")
		b.WriteString("provider = Other\n")
		b.WriteString("endpoint = " + endpoint + "\n")
		if region := getStr("region"); region != "" {
			b.WriteString("region = " + region + "\n")
		}
		b.WriteString("access_key_id = " + ak + "\n")
		b.WriteString("secret_access_key = " + sk + "\n")
		if getBool("path_style") {
			b.WriteString("force_path_style = true\n")
		}
		// 关键：rclone 默认在 copy 前会尝试 HeadBucket / CreateBucket 探测 bucket 是否存在。
		// 大多数 S3 兼容存储（腾讯 COS / Cloudflare R2 / 阿里 OSS）的 IAM 都不给
		// CreateBucket 权限，会返回 403，导致上传失败。
		// no_check_bucket = true 让 rclone 假设 bucket 已经存在，直接开始 PUT 对象。
		b.WriteString("no_check_bucket = true\n")

	default:
		return "", false, fmt.Errorf("unsupported type: %s", s.Type)
	}

	// ---- C1：加密存储追加 crypt 包裹节 ----
	// 密码不可用 / obscure 失败 → 跳过 crypt 节并告警（基础 section 保留，hasCrypt=false），
	// 与基础 section obscure 失败时"跳过该存储"的行为一致，禁止降级明文。
	if encryptionEnabled(cfg) {
		cryptSec, err := renderCryptSection(s)
		if err != nil {
			slog.Warn("存储已启用加密，但跳过 crypt 配置节", "storage", s.Name, "err", err)
			return b.String(), false, nil
		}
		b.WriteString("\n")
		b.WriteString(cryptSec)
		return b.String(), true, nil
	}
	return b.String(), false, nil
}

// rcloneObscure 调 `rclone obscure PASS` 编码密码
func rcloneObscure(plain string) (string, error) {
	cmd := exec.Command("rclone", "obscure", plain)
	out, err := cmd.Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

// writeKeyFile 把 SSH 私钥写到 /etc/backup-agent/keys/bc_<id>.key
func writeKeyFile(remoteName, key string) (string, error) {
	dir := "/etc/backup-agent/keys"
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	path := filepath.Join(dir, remoteName+".key")
	// 密钥必须以 \n 结尾
	content := key
	if !strings.HasSuffix(content, "\n") {
		content += "\n"
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		return "", err
	}
	return path, nil
}

// ---------- C1：crypt 包裹层 ----------

// renderCryptSection 生成 crypt 包裹节（C1）：
//
//	[bc_<id>_c]
//	type = crypt
//	remote = bc_<id>:
//	password = <obscure(加密密码)>
//	filename_encryption = standard|off
//	directory_name_encryption = true|false
//
// 加密密码按 key_mode 解析（center=Center 随 config 下发 / agent_local=本机 backup.key）；
// 密码不可用或 obscure 失败时返回错误，由调用方跳过该节并告警（禁止明文降级）。
func renderCryptSection(s client.Storage) (string, error) {
	enc, ok := encryptionBlock(s.Config)
	if !ok {
		return "", fmt.Errorf("storage config 缺少 encryption 块")
	}
	pass, err := resolveEncryptionPassword(enc)
	if err != nil {
		return "", err
	}
	obscured, err := rcloneObscure(pass)
	if err != nil {
		return "", fmt.Errorf("obscure 加密密码: %w", err)
	}

	name := remoteName(s.ID)
	var b strings.Builder
	b.WriteString(fmt.Sprintf("[%s_c]\n", name))
	b.WriteString("type = crypt\n")
	// remote 指向底层 remote 名，必须带冒号。S3 还要把 bucket 拼进来（remote = bc_<id>:bucket）：
	// crypt 只能加密 bucket 之后的路径，bucket 名不能被加密，否则底层 S3 remote 会把加密后的
	// 字符串当成 bucket 名去访问 → object not found。非 S3 无 bucket 概念，保持 bc_<id>:。
	cryptRemote := name + ":"
	if s.Type == "s3" {
		if bk, ok := s.Config["bucket"].(string); ok && strings.Trim(bk, "/") != "" {
			cryptRemote = name + ":" + strings.Trim(bk, "/")
		}
	}
	b.WriteString("remote = " + cryptRemote + "\n")
	b.WriteString("password = " + obscured + "\n")
	b.WriteString("filename_encryption = " + encryptionFilenameMode(enc) + "\n")
	b.WriteString(fmt.Sprintf("directory_name_encryption = %v\n", encryptionDirNameMode(enc)))
	return b.String(), nil
}

// encryptionBlock 取 storage config 里的 encryption 块（由 Center 经 websites() 随 config 下发）
func encryptionBlock(cfg map[string]interface{}) (map[string]interface{}, bool) {
	enc, ok := cfg["encryption"].(map[string]interface{})
	return enc, ok
}

// encryptionEnabled 存储级加密开关（缺省 false）
func encryptionEnabled(cfg map[string]interface{}) bool {
	enc, ok := encryptionBlock(cfg)
	if !ok {
		return false
	}
	return truthy(enc["enabled"])
}

// truthy 宽松布尔解析：bool 原样；字符串 "true"/"1" 为真
// （JSON 直解为 bool，字符串形态兼容手改配置/URL 参数等来源）
func truthy(v interface{}) bool {
	switch t := v.(type) {
	case bool:
		return t
	case string:
		return t == "true" || t == "1"
	}
	return false
}

// resolveEncryptionPassword 按 key_mode 取加密密码：
//   - center（默认）：来自 Center 随 config 下发的 encryption.password，为空则报错
//   - agent_local：来自本机 /etc/backup-agent/backup.key（读取并 TrimSpace），
//     文件缺失或内容为空则报错（错误信息指明路径）
func resolveEncryptionPassword(enc map[string]interface{}) (string, error) {
	if mode, _ := enc["key_mode"].(string); mode == "agent_local" {
		data, err := os.ReadFile(agentLocalKeyPath)
		if err != nil {
			return "", fmt.Errorf("key_mode=agent_local 但读取本机加密密钥 %s 失败: %w", agentLocalKeyPath, err)
		}
		key := strings.TrimSpace(string(data))
		if key == "" {
			return "", fmt.Errorf("key_mode=agent_local 但本机加密密钥 %s 内容为空", agentLocalKeyPath)
		}
		return key, nil
	}
	pass, _ := enc["password"].(string)
	if pass == "" {
		return "", fmt.Errorf("key_mode=center 但中心未提供加密密码（encryption.password 为空）")
	}
	return pass, nil
}

// encryptionFilenameMode filename_encryption：off 关闭，其余（含缺省）standard
func encryptionFilenameMode(enc map[string]interface{}) string {
	if mode, _ := enc["filename_encryption"].(string); mode == "off" {
		return "off"
	}
	return "standard"
}

// encryptionDirNameMode directory_name_encryption：缺省 true
func encryptionDirNameMode(enc map[string]interface{}) bool {
	v, ok := enc["directory_name_encryption"]
	if !ok {
		return true
	}
	return truthy(v)
}

// ---------- C5：conf/私钥残留清理 ----------

// pruneStaleSections（C5）删除 conf 中不在 valid 集合内的 bc_<id> / bc_<id>_c section 并重写文件。
// 正常路径下 writeRcloneConf 刚做过整文件重写，本函数是防御性兜底（如 conf 被外部改动）。
// 调用方需持有 Uploader 的锁（与 conf 写入同一把锁）。
func pruneStaleSections(confPath string, valid map[int64]bool) {
	data, err := os.ReadFile(confPath)
	if err != nil {
		return // conf 不存在/读不了：无可清理（写入失败时 UpdateStorages 已提前返回，不会到这里）
	}
	lines := strings.Split(string(data), "\n")
	out := make([]string, 0, len(lines))
	pruned := 0
	skipping := false
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "[") && strings.HasSuffix(trimmed, "]") {
			if staleRemoteSection(trimmed[1:len(trimmed)-1], valid) {
				skipping = true
				pruned++
				continue
			}
			skipping = false
		} else if skipping {
			continue // 丢弃失效 section 的内容行
		}
		out = append(out, line)
	}
	if pruned == 0 {
		return
	}
	if err := os.WriteFile(confPath, []byte(strings.Join(out, "\n")), 0o600); err != nil {
		slog.Warn("重写 rclone.conf 清理残留 section 失败", "err", err)
		return
	}
	slog.Info("已清理 rclone.conf 残留 section", "path", confPath, "count", pruned)
}

// staleRemoteSection 判断 section 名是否为失效的 bc_<id> / bc_<id>_c（id 不在 valid 集合）。
// 非 bc_<数字> 形态（用户自定义 section）一律返回 false，不碰。
func staleRemoteSection(name string, valid map[int64]bool) bool {
	if !strings.HasPrefix(name, "bc_") {
		return false
	}
	idStr := strings.TrimSuffix(strings.TrimPrefix(name, "bc_"), "_c")
	id, err := strconv.ParseInt(idStr, 10, 64)
	if err != nil {
		return false
	}
	return !valid[id]
}

// cleanupStaleKeyFiles（C5）删除 keys/ 下 id 不在 valid 集合的 bc_<id>.key 残留文件。
// 只删严格匹配 bc_<数字>.key 的文件；本次集合内的 id 一律不删。
// 调用方需持有 Uploader 的锁。
func cleanupStaleKeyFiles(valid map[int64]bool) {
	entries, err := os.ReadDir(agentKeysDir)
	if err != nil {
		if !os.IsNotExist(err) {
			slog.Warn("读取密钥目录失败，跳过残留清理", "dir", agentKeysDir, "err", err)
		}
		return
	}
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		if !strings.HasPrefix(name, "bc_") || !strings.HasSuffix(name, ".key") {
			continue
		}
		idStr := strings.TrimSuffix(strings.TrimPrefix(name, "bc_"), ".key")
		id, err := strconv.ParseInt(idStr, 10, 64)
		if err != nil || valid[id] {
			continue // 非 bc_<数字>.key 形态或仍在使用，不删
		}
		path := filepath.Join(agentKeysDir, name)
		if err := os.Remove(path); err != nil {
			slog.Warn("删除残留密钥文件失败", "file", path, "err", err)
			continue
		}
		slog.Info("已清理残留密钥文件", "file", path)
	}
}
